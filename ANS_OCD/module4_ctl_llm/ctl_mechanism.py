
"""
Conflict-Triggered Labeling (CTL) LLM interface.

Provides both a real OpenAI-compatible API caller and a Mock mode for offline
 development. The Mock mode is enabled by default (see LLM_CONFIG) to avoid
costs while the full pipeline is being stabilized.

Author: ANS-OCD project
"""
import os
import re
import random
from typing import Dict, List, Optional, Tuple

from ANS_OCD.config import LLM_CONFIG, get_openai_key, get_zhipu_key, ZHIPU_CONFIG


def _llm_chat_completion(prompt: str,
                          model: str = LLM_CONFIG["model"],
                          temperature: float = LLM_CONFIG["temperature"],
                          max_tokens: int = LLM_CONFIG["max_tokens"],
                          provider: str = LLM_CONFIG.get("provider", "openai")) -> str:
    """
    Call the configured LLM API (OpenAI or Zhipu) and return raw text.

    Falls back to Mock mode if the API key is missing or the request fails.
    """
    if provider == "zhipu":
        api_key = get_zhipu_key()
        api_base = ZHIPU_CONFIG.get("api_base", "https://open.bigmodel.cn/api/paas/v4/")
    else:
        api_key = get_openai_key()
        api_base = None

    if not api_key:
        print(f"[LLM] No API key found for provider '{provider}', falling back to Mock mode.")
        return mock_llm_response(prompt)

    try:
        if provider == "zhipu":
            import requests
            headers = {
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json",
            }
            payload = {
                "model": model,
                "messages": [{"role": "user", "content": prompt}],
                "temperature": temperature,
                "max_tokens": max_tokens,
            }
            resp = requests.post(f"{api_base.rstrip('/')}/chat/completions",
                                 headers=headers, json=payload, timeout=60)
            resp.raise_for_status()
            data = resp.json()
            return data["choices"][0]["message"]["content"].strip()

        # OpenAI-compatible path (legacy openai package)
        import openai
        openai.api_key = api_key
        if api_base:
            openai.api_base = api_base
        response = openai.ChatCompletion.create(
            model=model,
            messages=[{"role": "user", "content": prompt}],
            temperature=temperature,
            max_tokens=max_tokens,
        )
        return response.choices[0].message.content.strip()
    except Exception as e:
        print(f"[LLM] API call failed ({e}), falling back to Mock mode.")
        return mock_llm_response(prompt)


def mock_llm_response(prompt: str, mode: str = "auto") -> str:
    """
    Mock LLM response used during offline development.

    Two modes are supported:
    - "theme": mock a theme-validation response.
    - "conflict": mock a conflict-resolution response.
    - "auto": decide based on the prompt content.

    Parameters
    ----------
    prompt : str
        The prompt that would be sent to the real LLM.
    mode : str
        One of "theme", "conflict", or "auto".

    Returns
    -------
    response : str
        A deterministic-looking mock response.
    """
    if mode == "auto":
        if "conflict" in prompt.lower() or "heuristic" in prompt.lower():
            mode = "conflict"
        else:
            mode = "theme"

    if mode == "theme":
        # Extract the K_init value from the prompt.
        match = re.search(r"K_init\).*?by subspace clustering:\s*(\d+)", prompt, re.IGNORECASE)
        k_init = int(match.group(1)) if match else 2
        # Use a simple heuristic: trust the initial K but avoid huge numbers.
        k = max(1, min(k_init, 3))
        lines = [f"K: {k}"]
        for i in range(1, k + 1):
            lines.append(f"Theme_{i}: Research Topic {i}")
        lines.append("Merge: None")
        return "\n".join(lines)

    elif mode == "conflict":
        # Extract community ids from the GNN probabilities section.
        probs = re.findall(r"Community\s+(\d+):\s+([\d.]+)", prompt)
        if not probs:
            return "1"
        # Pick the top-2 communities by mocked probability.
        probs = sorted(probs, key=lambda x: float(x[1]), reverse=True)
        chosen = [int(probs[0][0])]
        if len(probs) > 1 and float(probs[1][1]) > 0.45:
            chosen.append(int(probs[1][0]))
        return ",".join(map(str, chosen))

    return ""


def validate_themes_with_llm(prompt: str) -> Tuple[int, Dict[int, str], List[List[int]]]:
    """
    Send a theme-validation prompt to the LLM and parse the response.

    Parameters
    ----------
    prompt : str
        Theme-validation prompt generated by prompt_engine.

    Returns
    -------
    k_final : int
        Final community count validated by the LLM.
    themes : Dict[int, str]
        Mapping from final community id to theme name.
    merges : List[List[int]]
        List of merge suggestions, each item is a list of cluster ids to merge.
    """
    if LLM_CONFIG.get("use_mock", True):
        raw = mock_llm_response(prompt, mode="theme")
    else:
        raw = _llm_chat_completion(prompt)

    k_final = 1
    themes: Dict[int, str] = {}
    merges: List[List[int]] = []

    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.lower().startswith("k:"):
            try:
                k_final = max(1, int(line.split(":", 1)[1].strip()))
            except ValueError:
                pass
        elif re.match(r"Theme_\d+\s*:", line, re.IGNORECASE):
            cid_str = line.split(":", 1)[0].lower().replace("theme_", "").strip()
            try:
                cid = int(cid_str)
                name = line.split(":", 1)[1].strip()
                themes[cid] = name
            except ValueError:
                pass
        elif line.lower().startswith("merge:"):
            merge_str = line.split(":", 1)[1].strip()
            if merge_str.lower() == "none":
                continue
            for group in merge_str.split(";"):
                ids = [int(x.strip()) for x in group.split(",") if x.strip().isdigit()]
                if len(ids) > 1:
                    merges.append(ids)

    return k_final, themes, merges


def resolve_conflict_with_llm(prompt: str) -> List[int]:
    """
    Send a conflict-resolution prompt to the LLM and parse the returned community ids.

    Parameters
    ----------
    prompt : str
        Conflict-resolution prompt generated by prompt_engine.

    Returns
    -------
    community_ids : List[int]
        List of community ids assigned to the conflict node (may be empty).
    """
    if LLM_CONFIG.get("use_mock", True):
        raw = mock_llm_response(prompt, mode="conflict")
    else:
        raw = _llm_chat_completion(prompt)

    raw = raw.strip().lower()
    if raw in ("", "none", "null"):
        return []
    ids = []
    for part in raw.split(","):
        part = part.strip().replace("community", "").replace("c", "")
        if part.isdigit():
            ids.append(int(part))
    return ids


